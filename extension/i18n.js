  const LANGUAGES = Object.freeze(Object.keys(MESSAGES));

  function resolveLanguage(preference, browserLanguage) {
    if (LANGUAGES.includes(preference)) return preference;
    return /^zh\b/i.test(String(browserLanguage || "")) ? "zh" : "en";
  }

  function translator(language) {
    const table = MESSAGES[language] || MESSAGES.zh;
    const t = (key, params = {}) => String(table[key] ?? MESSAGES.zh[key] ?? key)
      .replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
    t.language = MESSAGES[language] ? language : "zh";
    t.has = (key) => key in table;
    return t;
  }

  function apply(root, t) {
    root.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
    for (const attribute of ["title", "placeholder", "aria-label"]) {
      root.querySelectorAll(`[data-i18n-${attribute}]`).forEach((node) => {
        node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
      });
    }
  }

  globalThis.PageLensI18n = Object.freeze({ LANGUAGES, MESSAGES, resolveLanguage, translator, apply });
